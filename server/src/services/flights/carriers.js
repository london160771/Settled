export function parseFlightNumber(raw) {
  const m = /^\s*([A-Z0-9]{2})\s*(\d{1,4}[A-Z]?)\s*$/i.exec(raw || '');
  if (!m) return null;
  return {
    carrier: m[1].toUpperCase(),
    number: m[2].toUpperCase(),
    flightNumber: `${m[1]}${m[2]}`.toUpperCase(),
  };
}

export const carrierCountry = (carrier) => CARRIERS[String(carrier || '').toUpperCase()] || null;
